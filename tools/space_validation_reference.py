def sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def validate_author_tree(author_root, archive):
    """Verify every upstream byte BEFORE executing any imported author code."""
    root, pinned = Path(author_root).resolve(), Path(archive).resolve()
    if sha256(pinned) != AUTHOR_ARCHIVE_SHA256:
        raise ValueError("author archive hash differs from pinned Zenodo version")
    expected = {}
    with zipfile.ZipFile(pinned) as z:
        for member in z.infolist():
            if member.is_dir():
                continue
            relative = Path(*Path(member.filename).parts[1:])
            target = (root / relative).resolve()
            if not target.is_relative_to(root):
                raise ValueError("unsafe author archive path")
            expected[relative.as_posix()] = hashlib.sha256(z.read(member)).hexdigest()
    actual = {p.relative_to(root).as_posix(): sha256(p) for p in root.rglob("*")
              if p.is_file() and not ("__pycache__" in p.parts and p.suffix == ".pyc")}
    if actual != expected:
        raise ValueError("author tree does not exactly match pinned archive (excluding generated bytecode)")
    return expected


def gaussian_capture(distance_m, divergence_rad, receiver_radius_m, *, wavelength_m=780e-9,
                     pointing_sigma_rad=0.0):
    """Exact aperture integral of a Gaussian convolved with isotropic jitter.

    I(r)~exp(-2r²/w²), w²=w0²+(theta*L)², w0=lambda/(pi*theta).
    Independent 2D jitter has covariance (L*sigma)² I; hence w_eff²=w²+4(L*sigma)².
    Encircled power is 1-exp(-2a²/w_eff²). No loss from a transmitter aperture is
    inserted: published eta_dif's sender_aperture_radius is unused by that code.
    """
    values = (distance_m, divergence_rad, receiver_radius_m, wavelength_m, pointing_sigma_rad)
    if not all(math.isfinite(float(x)) for x in values):
        raise ValueError("finite SI optical parameters required")
    if distance_m < 0 or divergence_rad <= 0 or receiver_radius_m <= 0 or wavelength_m <= 0 or pointing_sigma_rad < 0:
        raise ValueError("positive divergence/aperture/wavelength and nonnegative distance/jitter required")
    waist = wavelength_m / (math.pi * divergence_rad)
    variance = waist**2 + (distance_m * divergence_rad)**2 + 4 * (distance_m * pointing_sigma_rad)**2
    return -math.expm1(-2 * receiver_radius_m**2 / variance)


def atmospheric_capture(elevation_deg, *, zenith_transmission=0.8):
    if not math.isfinite(elevation_deg) or not 0 < zenith_transmission <= 1:
        raise ValueError("finite elevation and zenith transmission in (0,1] required")
    if elevation_deg <= 0:
        return 0.0
    return zenith_transmission ** (1 / math.sin(math.radians(elevation_deg)))


def ground_ecef(latitude_deg, longitude_deg, altitude_m=0):
    if not -90 <= latitude_deg <= 90 or not math.isfinite(longitude_deg) or not math.isfinite(altitude_m):
        raise ValueError("valid WGS84 latitude, longitude and altitude required")
    latitude, longitude = np.deg2rad([latitude_deg, longitude_deg])
    e2 = WGS84_F * (2 - WGS84_F)
    normal = WGS84_A_KM / math.sqrt(1 - e2 * math.sin(latitude)**2)
    height = altitude_m / 1000
    return np.array([(normal + height) * math.cos(latitude) * math.cos(longitude),
                     (normal + height) * math.cos(latitude) * math.sin(longitude),
                     ((1 - e2) * normal + height) * math.sin(latitude)])


def relative_geometry(left, right, *, limb_margin_km=80.0, require_los=True):
    """LOS via quadratic segment/ellipsoid roots, independent of nearest point.

    Earth rotation is restored for inertial transverse velocity, required by
    beacon-to-outgoing point ahead. Radial velocity is invariant under rotation.
    """
    if left.get("frame") != "ECEF" or right.get("frame") != "ECEF":
        raise ValueError("common ECEF required")
    if abs(left["at_s"] - right["at_s"]) > 1e-6:
        raise ValueError("common epoch required")
    origin = np.asarray(left["ecef_km"], dtype=float)
    destination = np.asarray(right["ecef_km"], dtype=float)
    delta = destination - origin
    distance = float(np.linalg.norm(delta))
    if distance <= 0:
        raise ValueError("distinct endpoints required")
    direction = delta / distance
    relative = np.asarray(right["velocity_ecef_km_s"]) - np.asarray(left["velocity_ecef_km_s"])
    radial = float(np.dot(direction, relative))
    inertial = relative + np.cross([0.0, 0.0, OMEGA_RAD_S], delta)
    transverse = float(np.linalg.norm(np.cross(inertial, direction)))
    axes = np.array([WGS84_A_KM + limb_margin_km] * 2 + [WGS84_B_KM + limb_margin_km])
    p, d = origin / axes, delta / axes
    coeff = (float(d @ d), 2 * float(p @ d), float(p @ p) - 1)
    discriminant = coeff[1]**2 - 4 * coeff[0] * coeff[2]
    blocked = float(p @ p) <= 1 or float((p + d) @ (p + d)) <= 1
    if discriminant >= 0:
        roots = [(-coeff[1] + sign * math.sqrt(discriminant)) / (2 * coeff[0]) for sign in (-1, 1)]
        blocked |= max(roots) >= 0 and min(roots) <= 1
    return {"range_km": distance, "radial_velocity_km_s": radial,
            "transverse_velocity_km_s": transverse, "earth_obstructed": bool(blocked and require_los),
            "flight_time_s": distance * 1000 / C_M_S,
            "point_ahead_urad": 2 * transverse * 1000 / C_M_S * 1e6,
            "angular_tracking_rate_rad_s": transverse / distance}


def ground_geometry(state, station, altitude_m=0):
    ground = ground_ecef(*station, altitude_m)
    ground_state = {"ecef_km": ground, "velocity_ecef_km_s": [0.0, 0.0, 0.0],
                    "at_s": state.get("at_s", state.get("at_network_s", 0)), "frame": "ECEF"}
    target = {**state, "at_s": ground_state["at_s"]}
    result = relative_geometry(ground_state, target, limb_margin_km=0, require_los=False)
    lat, lon = np.deg2rad(station)
    transform = np.array([[-math.sin(lon), math.cos(lon), 0],
        [-math.sin(lat)*math.cos(lon), -math.sin(lat)*math.sin(lon), math.cos(lat)],
        [math.cos(lat)*math.cos(lon), math.cos(lat)*math.sin(lon), math.sin(lat)]])
    east, north, up = transform @ (np.asarray(state["ecef_km"]) - ground)
    result.update(elevation_deg=math.degrees(math.atan2(up, math.hypot(east, north))),
                  azimuth_deg=math.degrees(math.atan2(east, north)) % 360)
    return result


def carrier_doppler(radial_km_s, wavelength_nm):
    if wavelength_nm <= 0:
        raise ValueError("positive wavelength required")
    # First-order nonrelativistic delta-f=-v_radial/lambda, signed for receding.
    return -radial_km_s * 1000 / (wavelength_nm * 1e-9)


def bernoulli_photons(seed, attempts, probability):
    """Raw emitted/transmitted-event count, never a final QKD result."""
    if type(attempts) is not int or attempts < 0 or not 0 <= probability <= 1:
        raise ValueError("nonnegative integer attempts and probability in [0,1] required")
    rng = np.random.default_rng(seed)
    return {"seed": seed, "emitted": attempts, "detected": int(rng.binomial(attempts, probability)),
            "expected": attempts * probability,
            "std": math.sqrt(attempts * probability * (1-probability))}


def run_author_probe(author_root, cases, *, include_jitter=False, archive=None):
    """Execute intact published code. Call in an isolated process (libs imports)."""
    root = Path(author_root).resolve()
    archive = archive or Path(__file__).resolve().parents[1] / "outputs/space_validation_preparation_20261010/zenodo-6384558-v1.1.0.zip"
    expected = validate_author_tree(root, archive)
    common = root / "scenarios" / "three_satellites" / "common_functions.py"
    if not common.is_file() or not (root / "LICENSE").is_file():
        raise ValueError("complete licensed author archive required")
    sys.path.insert(0, str(root))
    spec = importlib.util.spec_from_file_location("wallnofer_archived_common", common)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    before = {str(p.relative_to(root)): sha256(p) for p in root.rglob("*.py")}
    rows = []
    for case in cases:
        sigma = case.get("pointing_sigma_rad", 0) if include_jitter else 0
        actual = module.eta_dif(case["distance_m"], case["divergence_rad"], case.get("sender_radius_m", .15),
                                case["receiver_radius_m"], wavelength=case.get("wavelength_m", 780e-9),
                                pointing_error_sigma=sigma)
        rows.append({"case_id": case["case_id"], "author_eta": float(actual),
                     "analytical_eta": gaussian_capture(case["distance_m"], case["divergence_rad"],
                        case["receiver_radius_m"], wavelength_m=case.get("wavelength_m", 780e-9),
                        pointing_sigma_rad=sigma),
                     "author_atmosphere": float(module.eta_atm(math.radians(case.get("elevation_deg", 90))))})
    after = {str(p.relative_to(root)): sha256(p) for p in root.rglob("*.py")}
    return {"cases": rows, "source_hashes": before, "archive_members_verified": expected,
            "upstream_matches_pinned_archive": True, "upstream_unchanged": before == after,
            "license_sha256": sha256(root / "LICENSE"), "commit": AUTHOR_COMMIT}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--author-root", type=Path, required=True)
    parser.add_argument("--cases", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--include-jitter", action="store_true")
    args = parser.parse_args()
    result = run_author_probe(args.author_root, json.loads(args.cases.read_text()), include_jitter=args.include_jitter)
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
