"""Global operational readback and satellite-first globe, in source or frozen Qt."""
import json
from pathlib import Path


def validate_global_globe(destination,provider):
    from PySide6.QtCore import QCoreApplication,QEvent,QPoint,QPointF,Qt
    from PySide6.QtGui import QWheelEvent
    from PySide6.QtTest import QTest
    from PySide6.QtWidgets import QApplication
    import shiboken6
    from .responsive_validation import wait_for_node_presentation
    from .screens.topology import TopologyScreen
    from .widgets.figures import marker_kind,marker_side
    from .widgets.geo_map import GeoMap
    from .widgets.geo_view import MAP_TO_GLOBE_SPAN_M,GLOBE_TO_MAP_SPAN_M
    from .widgets.network_views import build_net_model
    from .widgets.orbit_globe import OrbitGlobe
    from .widgets.satellite_telemetry import value

    app=QApplication.instance();out=Path(destination);out.mkdir(parents=True,exist_ok=True)
    checks={};geo=None;screen=None
    report={'schema':'orion.global-globe-validation.v1','passed':False,'checks':checks,
        'qt_platform':app.platformName(),'physical_action_performed':False,
        'scope':'shared real backend snapshots generated by simulated acquisitions; Qt-owned input events, not physical mouse/hardware qualification'}

    def settle(wait=4):
        app.processEvents();QCoreApplication.sendPostedEvents(None,QEvent.Type.DeferredDelete)
        app.processEvents();QTest.qWait(wait);app.processEvents()

    report['presentation_waits']=[]
    def presented(window,phase):
        evidence=wait_for_node_presentation(window,screen._snap,screen._net,timeout_ms=5000)
        report['presentation_waits'].append({'node_id':window.node_id,'phase':phase,**evidence})
        return evidence
    def refresh(steps=0):
        for _ in range(steps):provider.service.network_step()
        provider.refresh();snapshot=provider.snapshot()
        if screen is not None:
            screen.apply(snapshot)
            for opened in tuple(screen.node_windows.windows.values()):presented(opened,'refresh')
        settle();return snapshot

    try:
        snapshot=refresh(5);model=build_net_model(snapshot)
        operations=snapshot.live.technologies.get('global_operations',{})
        expected={node.id for node in model.nodes if node.physical_type=='satellite' and (model.satellites or {}).get(node.id,{}).get('ecef_km')}
        expected_orbits={node.id for node in model.nodes if node.physical_type=='satellite' and (model.satellites or {}).get(node.id,{}).get('orbit_ecef_km')}
        checks['backend_global_demands_and_component_audit']=bool(operations.get('demands')) and len(operations.get('components',[]))==len(model.nodes)
        geo=GeoMap();geo.setWindowFlags(Qt.WindowType.Window|Qt.WindowType.FramelessWindowHint)
        geo.resize(1280,900);geo.set_model(model);geo.show();geo.set_mode('globe',camera=(0.,0.,1.));settle(400)
        items=geo.globe.orbital_items()
        checks['all_satellites_and_orbits_including_earth_occluded']=bool(expected) and {item['id'] for item in items}==expected and set(geo.globe._orbit_paths)==expected_orbits
        resolutions=[];sizes_ok=labels_ok=priority_ok=True
        for width,height in [(640,480),(3440,1440)]:
            geo.resize(width,height);settle(400);globe=geo.globe;icons=globe.orbital_items();ground=globe.ground_marker_geometry()
            sizes_ok &= (geo.size().width()==width and geo.size().height()==height and
                         all(item['size_px']<=14. and item['size_px']<marker_side(item['kind']) for item in ground) and
                         all(item['size_px']>=32. and item['hit'].width()>=48. and geo.rect().contains(item['hit'].toRect()) for item in icons))
            priority_ok &= all(globe.hit(item['centre'])==('node',item['id']) for item in icons)
            labels=globe.label_geometry()
            labels_ok &= all(node.network_role in ('endpoint','core') for node,_,_ in labels)
            labels_ok &= all(not rect.intersects(other) for index,(_,_,rect) in enumerate(labels) for _,_,other in labels[index+1:])
            geo.grab().save(str(out/f'global-globe-{width}.png'))
            resolutions.append({'width':width,'height':height,'actual_width':geo.width(),'actual_height':geo.height(),'satellites':len(icons),
                'earth_occluded':[item['id'] for item in icons if item['hidden']],
                'ground_marker_count':len(ground),'max_ground_px':max((item['size_px'] for item in ground),default=0),
                'ground_labels':len(labels)})
        checks['discreet_ground_and_large_satellite_targets_at_both_resolutions']=sizes_ok
        checks['satellite_selection_has_priority_at_both_resolutions']=priority_ok
        checks['endpoint_core_labels_remain_decluttered']=labels_ok
        # Real button and wheel paths use the existing shared-camera controller.
        geo.resize(1280,900);geo.set_mode('map');settle()
        geo.set_view_state((-43.17,-22.95,geo.width()/(MAP_TO_GLOBE_SPAN_M*.99)))
        def wheel(delta):
            widget=geo.renderer;point=QPointF(widget.width()/2,widget.height()/2)
            event=QWheelEvent(point,QPointF(widget.mapToGlobal(point.toPoint())),QPoint(),QPoint(0,delta),
                Qt.MouseButton.NoButton,Qt.KeyboardModifier.NoModifier,Qt.ScrollPhase.NoScrollPhase,False)
            QApplication.sendEvent(widget,event);settle()
        wheel(-120);entered=geo.mode=='globe';wheel(600)
        stays_globe=geo.mode=='globe'
        for _ in range(4):
            wheel(120);stays_globe &= geo.mode=='globe'
        wheel(120)
        returned=geo.mode=='map' and abs(geo.metres_per_px*geo.width()-GLOBE_TO_MAP_SPAN_M)<1
        wheel(-120)
        checks['button_scroll_and_zoom_hysteresis']=entered and stays_globe and returned and geo.mode=='map'
        report['globe_retained_after_nine_scroll_steps']=stays_globe
        geo.shutdown();geo.close();geo.deleteLater();geo=None;settle()

        screen=TopologyScreen();screen.resize(1280,900);screen.apply(snapshot);screen.show();settle()
        screen.geo.set_mode('globe',camera=(0.,0.,1.));settle(400)
        signals=[];screen.geo.node_selected.connect(signals.append)
        opened=True
        for item in screen.geo.globe.orbital_items():
            QTest.mouseClick(screen.geo.globe,Qt.MouseButton.LeftButton,pos=item['centre'].toPoint());settle()
            window=screen.node_windows.windows.get(item['id'])
            if window is not None:presented(window,'open-all-satellites')
            opened &= window is not None and window.satellite_panel.isVisible() and not window.chart.isVisible()
            screen.node_windows.close_all();settle()
        checks['all_satellites_open_physical_device_windows']=opened and set(signals)==expected
        isl_id=next((ident for ident,state in model.satellites.items() if state.get('isl_links')),None)
        if isl_id is None:raise ValueError('no configured satellite ISL available for inspection')
        screen.geo.node_selected.emit(isl_id);settle();window=screen.node_windows.windows[isl_id]
        presented(window,'open-isl')
        panel=window.satellite_panel;state=snapshot.live.satellites[isl_id]
        isl_ids={link['link_id'] for link in state['isl_links']}
        checks['isl_is_not_presented_as_ground_station']=not isl_ids.intersection(panel.stations) and all(
            marker_kind(model.node(item['station_id']))!='satellite' for bridge in state.get('bridges',[])
            if 'satellite_isl' not in bridge.get('technologies',[]) for item in bridge.get('connections',[]))
        checks['live_housekeeping_and_isl_metrics_use_shared_snapshot']=panel.orbital.texts()['Posição ECEF · km']==value(state.get('ecef_km')) and bool(panel.isl.rows)
        checks['demand_states_in_floating_window_match_backend']=all(
            demand['state'] in panel.operations.value(f'Demanda {index}') for index,demand in enumerate(state.get('global_demands',[]),1))
        window.scroll.verticalScrollBar().setValue(0);settle();screen.grab().save(str(out/'satellite-global-orbit.png'))
        window.scroll.ensureWidgetVisible(panel.isl,0,8);settle();screen.grab().save(str(out/'satellite-global-isl.png'))
        window.scroll.ensureWidgetVisible(panel.operations,0,8);settle();screen.grab().save(str(out/'satellite-global-demands.png'))
        window.scroll.verticalScrollBar().setValue(window.scroll.verticalScrollBar().maximum());settle();screen.grab().save(str(out/'satellite-global-isl-and-demand.png'))
        checks['scrolling_reaches_satellite_details']=not panel.details.visibleRegion().isEmpty()
        screen.technology_panel.open();settle();dialog=screen.technology_panel.dialog;view=dialog.global_view
        checks['global_demand_and_component_tables_match_backend']=view.demands.rowCount()==len(operations.get('demands',[])) and view.components.rowCount()==len(operations.get('components',[]))
        view._capture();captured=view.evidence.toPlainText();view.demands.selectRow(min(2,view.demands.rowCount()-1))
        table=view.demands;item=table.item(0,3);selection=table.currentRow();bar=table.verticalScrollBar();bar.setValue(bar.maximum()//2);scroll=bar.value()
        stable_data=screen._net;failures=[];old_renderers=[]
        for index in range(10):
            old=screen.geo.renderer;screen.geo.mode_button.click();settle();old_renderers.append(old)
            if (shiboken6.isValid(old) or screen.geo.resource_stats()['renderer_instances']!=1 or screen._net is not stable_data or
                screen._selection!=('node',isl_id) or screen.node_windows.windows.get(isl_id) is not window or
                screen.technology_panel.dialog is not dialog or table.item(0,3) is not item or table.currentRow()!=selection or bar.value()!=scroll):failures.append(index)
        settle(400)
        checks['ten_mode_swaps_preserve_selection_panels_tables_and_release_resources']=not failures and not any(shiboken6.isValid(old) for old in old_renderers) and not screen.geo.resource_stats()['transition_raster']
        latest=refresh(3)
        checks['live_tables_update_without_replacing_rows_or_captured_evidence']=table.item(0,3) is item and view.evidence.toPlainText()==captured
        view.tabs.setCurrentIndex(0);settle();view.grab().save(str(out/'global-demands.png'))
        view.tabs.setCurrentIndex(1);settle();view.grab().save(str(out/'global-components.png'))
        latest_operations=latest.live.technologies['global_operations']
        checks['no_certified_keys_or_physical_actions']=latest_operations.get('certified_secret_bits',0)==0 and latest.live.technologies['physical_actuation'] is False
        report.update(passed=all(checks.values()),check_count=len(checks),resolutions=resolutions,
            counts={'nodes':len(model.nodes),'links':len(model.links),'satellites':len(expected),'orbits':len(expected_orbits),
                    'demands':len(operations.get('demands',[])),'sessions':len(snapshot.live.technologies['sessions'])},
            isl_selection=isl_id,swap_failures=failures,backend_state_counts=latest_operations.get('state_counts',{}))
    except Exception as exc:report['error']=f'{type(exc).__name__}: {exc}'
    finally:
        if geo is not None:geo.shutdown();geo.close();geo.deleteLater()
        if screen is not None:screen.shutdown();screen.close();screen.deleteLater()
        settle()
    (out/'report.json').write_text(json.dumps(report,indent=2,ensure_ascii=False,default=str),encoding='utf-8')
    return report
